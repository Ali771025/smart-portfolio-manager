"""
Trade transaction ledger.

Every BUY or SELL is an immutable event record.  We never mutate
a transaction — corrections are done via compensating entries.
ALL monetary fields are NUMERIC(24, 8).
"""

import uuid
from datetime import date, datetime
from decimal import Decimal

from sqlalchemy import (
    String, Text, Numeric, DateTime, ForeignKey,
    Index, Enum as PGEnum, CheckConstraint, UniqueConstraint, Integer, text,
)
from sqlalchemy.dialects.postgresql import UUID as PG_UUID
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.database import Base
from app.models.mixins import UUIDMixin, TimestampMixin
from app.models.enums import TransactionType

from typing import TYPE_CHECKING
if TYPE_CHECKING:
    from app.models.portfolio import Portfolio
    from app.models.asset import Asset


class Transaction(UUIDMixin, TimestampMixin, Base):
    """
    Immutable ledger entry for a BUY or SELL operation.

    Business rules enforced at DB level:
      • quantity > 0
      • price_per_unit >= 0
      • fees >= 0
    """
    __tablename__ = "transactions"

    __table_args__ = (
        # ── Performance indexes ──────────────────────────
        Index("ix_txn_portfolio_asset", "portfolio_id", "asset_id"),
        Index("ix_txn_executed_at", "executed_at"),
        Index("ix_txn_portfolio_executed", "portfolio_id", "executed_at"),
        UniqueConstraint("portfolio_id", "idempotency_key", name="uq_txn_portfolio_idempotency"),
        UniqueConstraint("reference_hash", name="uq_transactions_reference_hash"),

        # ── Domain integrity constraints ─────────────────
        CheckConstraint("quantity > 0", name="ck_txn_quantity_positive"),
        CheckConstraint("price_per_unit >= 0", name="ck_txn_price_non_negative"),
        CheckConstraint("fees >= 0", name="ck_txn_fees_non_negative"),
    )

    # ── Foreign Keys ─────────────────────────────────────
    portfolio_id: Mapped[uuid.UUID] = mapped_column(
        PG_UUID(as_uuid=True),
        ForeignKey("portfolios.id", ondelete="CASCADE"),
        nullable=False,
    )
    asset_id: Mapped[uuid.UUID] = mapped_column(
        PG_UUID(as_uuid=True),
        ForeignKey("assets.id", ondelete="RESTRICT"),
        nullable=False,
    )

    # ── Trade details (ALL NUMERIC — NO FLOATS) ─────────
    transaction_type: Mapped[TransactionType] = mapped_column(
        PGEnum(TransactionType, name="transaction_type_enum", create_type=True),
        nullable=False,
        index=True,
    )
    quantity: Mapped[Decimal] = mapped_column(
        Numeric(24, 8),
        nullable=False,
        comment="Number of units bought or sold (fractional allowed)",
    )
    price_per_unit: Mapped[Decimal] = mapped_column(
        Numeric(24, 8),
        nullable=False,
        comment="Execution price per unit in the portfolio's base currency",
    )
    fees: Mapped[Decimal] = mapped_column(
        Numeric(24, 8),
        nullable=False,
        default=Decimal("0.00000000"),
        comment="Broker commission + exchange fees",
    )
    total_amount: Mapped[Decimal] = mapped_column(
        Numeric(24, 8),
        nullable=False,
        comment="quantity * price_per_unit (+ fees for BUY, - fees for SELL)",
    )
    currency: Mapped[str] = mapped_column(
        String(3), nullable=False, default="USD",
    )
    realized_pnl: Mapped[Decimal] = mapped_column(
        Numeric(24, 8),
        nullable=False,
        default=Decimal("0.00000000"),
        comment="Realized profit/loss generated by this transaction",
    )
    wac_at_execution: Mapped[Decimal] = mapped_column(
        Numeric(24, 8),
        nullable=False,
        default=Decimal("0.00000000"),
        comment="Weighted average cost snapshot before this transaction",
    )
    reference_hash: Mapped[str] = mapped_column(
        String(64),
        nullable=False,
        index=True,
        comment="Deterministic SHA-256 for import idempotency.",
    )
    idempotency_key: Mapped[str] = mapped_column(
        String(128),
        nullable=False,
        index=True,
    )
    version_id: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=1,
        server_default=text("1"),
    )

    # ── Broker import audit fields (nullable for legacy/manual transactions) ──
    import_batch_id: Mapped[uuid.UUID | None] = mapped_column(
        PG_UUID(as_uuid=True),
        ForeignKey("import_jobs.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
        comment="Import job that produced this trade, when applicable.",
    )
    source_broker: Mapped[str | None] = mapped_column(String(32), nullable=True)
    source_file_hash: Mapped[str | None] = mapped_column(String(64), nullable=True, index=True)
    source_row_number: Mapped[int | None] = mapped_column(Integer, nullable=True)
    raw_type: Mapped[str | None] = mapped_column(String(64), nullable=True)
    normalized_type: Mapped[str | None] = mapped_column(String(32), nullable=True, index=True)
    net_amount: Mapped[Decimal | None] = mapped_column(Numeric(24, 8), nullable=True)
    fee_or_adjustment: Mapped[Decimal | None] = mapped_column(Numeric(24, 8), nullable=True)
    cash_effect: Mapped[Decimal | None] = mapped_column(Numeric(24, 8), nullable=True)
    debit_amount: Mapped[Decimal | None] = mapped_column(Numeric(24, 8), nullable=True)
    credit_amount: Mapped[Decimal | None] = mapped_column(Numeric(24, 8), nullable=True)
    balance_after: Mapped[Decimal | None] = mapped_column(Numeric(24, 8), nullable=True)

    # ── Execution metadata ───────────────────────────────
    executed_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        index=True,
        comment="Actual trade execution timestamp (may differ from created_at)",
    )
    notes: Mapped[str | None] = mapped_column(Text, nullable=True)
    source_metadata: Mapped[dict | None] = mapped_column(
        JSONB,
        nullable=True,
        comment="Optional source payload (broker, row number, import context).",
    )

    # ── External reference (e.g., broker confirmation ID) ──
    external_ref: Mapped[str | None] = mapped_column(
        String(255), nullable=True, unique=True,
    )

    # ── Relationships ────────────────────────────────────
    portfolio: Mapped["Portfolio"] = relationship(back_populates="transactions")
    asset: Mapped["Asset"] = relationship(back_populates="transactions")

    __mapper_args__ = {"version_id_col": version_id}

    def __repr__(self) -> str:
        return (
            f"<Transaction {self.transaction_type.value} "
            f"{self.quantity}x @{self.price_per_unit}>"
        )

    @property
    def side(self) -> TransactionType:
        return self.transaction_type

    @side.setter
    def side(self, value: TransactionType) -> None:
        self.transaction_type = value

    @property
    def trade_date(self) -> date:
        return self.executed_at.date()

    @property
    def unit_price(self) -> Decimal:
        return self.price_per_unit

    @unit_price.setter
    def unit_price(self, value: Decimal) -> None:
        self.price_per_unit = value

    @property
    def gross_amount(self) -> Decimal:
        return self.total_amount

    @gross_amount.setter
    def gross_amount(self, value: Decimal) -> None:
        self.total_amount = value

    @property
    def raw_description(self) -> str | None:
        return self.notes

    @raw_description.setter
    def raw_description(self, value: str | None) -> None:
        self.notes = value


# Backward/forward compatible alias for Phase 2 terminology.
Trade = Transaction

